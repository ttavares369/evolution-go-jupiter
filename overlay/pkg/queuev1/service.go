// ErrInvalid identifies invalid input without echoing message bodies or media.
var ErrInvalid = errors.New("invalid queue request")

const (
	serviceOperationTimeout = 85 * time.Second
	serviceWorkTimeout      = 70 * time.Second // Reserve 15s for durable bookkeeping.
	serviceMaxTextBytes     = 64 << 10
	serviceMaxCaptionBytes  = 4096
	serviceMaxImageSide     = 8192
	serviceMaxImagePixels   = 32_000_000
	serviceMaxMessageID     = 64
)

// SendRequest uses stable caller identities, but never accepts an owner identity.
// Text/caption limits are UTF-8 byte limits (64 KiB/4096). Images are standard,
// padded base64, at most 16 MiB decoded, 8192 per side and 32 million pixels.
// MIME and the lowercase hexadecimal SHA-256 must match the decoded image.
// Fields belonging to the other kind must be empty; no input is silently dropped.
type SendRequest struct {
	AttemptID        string `json:"attemptId"`
	LogicalMessageID string `json:"logicalMessageId"`
	MessageID        string `json:"messageId"`
	To               string `json:"to"`
	Text             string `json:"text"`
	Caption          string `json:"caption"`
	MIME             string `json:"mime"`
	ImageSHA256      string `json:"imageSha256"`
	ImageBase64      string `json:"imageBase64"`
	Kind             string `json:"kind"`
	ValidUntil       string `json:"validUntil,omitempty"`
}

type PresenceRequest struct {
	To         string `json:"to"`
	DurationMS int    `json:"durationMs"`
}

// Service is inert until called and safe to share. Ownership is generated by the
// server per admission, never reused to recover execution rights after a crash.
type Service struct {
	ledger    Ledger
	transport Transport
	now       func() time.Time
}

func NewService(ledger Ledger, transport Transport) *Service {
	return &Service{ledger: ledger, transport: transport, now: time.Now}
}

func serviceUUID(id string) bool {
	u, err := uuid.Parse(id)
	return err == nil && u != uuid.Nil && u.String() == id
}

func serviceMessageID(id string) bool {
	if len(id) == 0 || len(id) > serviceMaxMessageID {
		return false
	}
	for _, c := range []byte(id) {
		if !(c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9') {
			return false
		}
	}
	return true
}

func serviceInvalid(field string) error { return fmt.Errorf("%w: %s", ErrInvalid, field) }

func serviceMessage(req SendRequest) (Message, string, error) {
	if !serviceUUID(req.AttemptID) || !serviceUUID(req.LogicalMessageID) {
		return Message{}, "", serviceInvalid("canonical attempt/logical UUID required")
	}
	if !serviceMessageID(req.MessageID) {
		return Message{}, "", serviceInvalid("messageId must be 1-64 ASCII alphanumeric characters")
	}
	if len(req.To) > 255 || !utf8.ValidString(req.To) {
		return Message{}, "", serviceInvalid("to")
	}
	if _, err := queueTarget(req.To); err != nil {
		return Message{}, "", serviceInvalid("canonical PN/LID/group JID required")
	}
	if !utf8.ValidString(req.Text) || !utf8.ValidString(req.Caption) || len(req.Text) > serviceMaxTextBytes || len(req.Caption) > serviceMaxCaptionBytes {
		return Message{}, "", serviceInvalid("text/caption UTF-8 or byte limit")
	}
	if !canonicalDeadline(req.ValidUntil) {
		return Message{}, "", serviceInvalid("validUntil must be canonical UTC ISO milliseconds")
	}
	msg := Message{Kind: req.Kind, To: req.To, Text: req.Text, Caption: req.Caption, MIME: req.MIME, ImageSHA256: req.ImageSHA256, ValidUntil: req.ValidUntil}
	switch req.Kind {
	case "text":
		if strings.TrimSpace(req.Text) == "" || req.Caption != "" || req.MIME != "" || req.ImageSHA256 != "" || req.ImageBase64 != "" {
			return Message{}, "", serviceInvalid("text fields")
		}
	case "image":
		if req.Text != "" || len(req.ImageSHA256) != 64 || req.ImageBase64 == "" || len(req.ImageBase64) > base64.StdEncoding.EncodedLen(MaxImageBytes) || strings.ContainsAny(req.ImageBase64, "\r\n") {
			return Message{}, "", serviceInvalid("image fields or base64 size")
		}
		data, err := base64.StdEncoding.Strict().DecodeString(req.ImageBase64)
		if err != nil || len(data) == 0 || len(data) > MaxImageBytes {
			return Message{}, "", serviceInvalid("image base64 or decoded size")
		}
		sum := sha256.Sum256(data)
		if req.ImageSHA256 != hex.EncodeToString(sum[:]) {
			return Message{}, "", serviceInvalid("image SHA-256")
		}
		mime := http.DetectContentType(data)
		var format string
		switch mime {
		case "image/jpeg":
			format = "jpeg"
		case "image/png":
			format = "png"
		case "image/webp":
			format = "webp"
		default:
			return Message{}, "", serviceInvalid("unsupported image MIME")
		}
		if req.MIME != mime {
			return Message{}, "", serviceInvalid("image MIME mismatch")
		}
		config, decodedFormat, err := image.DecodeConfig(bytes.NewReader(data))
		if err != nil || decodedFormat != format || config.Width <= 0 || config.Height <= 0 || config.Width > serviceMaxImageSide || config.Height > serviceMaxImageSide || int64(config.Width)*int64(config.Height) > serviceMaxImagePixels {
			return Message{}, "", serviceInvalid("image configuration or dimensions")
		}
		msg.ImageBytes = data
	default:
		return Message{}, "", serviceInvalid("kind must be text or image")
	}
	// A versioned, fixed-field JSON tuple is unambiguous, independent of map
	// ordering, identities, base64 spelling and mutable transport buffers. Only
	// this digest reaches the ledger, never the tuple, body or decoded media.
	tuple := []string{Contract + "/content/1", msg.Kind, msg.To, msg.Text, msg.Caption, msg.MIME, msg.ImageSHA256}
	if req.ValidUntil != "" {
		tuple = append(tuple, req.ValidUntil)
	}
	canonical, err := json.Marshal(tuple)
	if err != nil {
		return Message{}, "", serviceInvalid("content encoding")
	}
	sum := sha256.Sum256(canonical)
	return msg, hex.EncodeToString(sum[:]), nil
}

func serviceMatches(a Attempt, b Binding) bool {
	return a.InstanceID == b.InstanceID && a.AttemptID == b.AttemptID && a.LogicalMessageID == b.LogicalMessageID && a.MessageID == b.MessageID && a.ContentHash == b.ContentHash && a.ValidUntil == b.ValidUntil
}

// Send returns durable outcomes, including rejected/uncertain, with nil error.
// nil error does NOT mean accepted: inspect State and Code. In particular a new
// attempt rejected as logical_pending/logical_accepted says nothing about the
// absence of an earlier commercial effect for that logical message.
// Errors (including failed/ambiguous SQL commits or session unlocks) never return
// a purported accepted result. A surviving preparing/sending/uncertain attempt
// is replayed verbatim, never recovered, expired, released or sent again here.
func (s *Service) Send(ctx context.Context, instanceID string, req SendRequest) (Attempt, error) {
	if err := ctx.Err(); err != nil {
		return Attempt{}, err
	}
	if !serviceUUID(instanceID) {
		return Attempt{}, serviceInvalid("canonical instance UUID required")
	}
	msg, hash, err := serviceMessage(req)
	if err != nil {
		return Attempt{}, err
	}
	if s == nil || s.ledger == nil || s.transport == nil {
		return Attempt{}, ErrUnavailable
	}
	b := Binding{InstanceID: instanceID, AttemptID: req.AttemptID, LogicalMessageID: req.LogicalMessageID, MessageID: req.MessageID, ContentHash: hash, ValidUntil: req.ValidUntil}
	if err := ctx.Err(); err != nil {
		return Attempt{}, err
	}
	prior, err := s.ledger.Lookup(ctx, instanceID, req.AttemptID)
	if err == nil {
		if !serviceMatches(prior, b) {
			return Attempt{}, ErrConflict
		}
		return prior, nil
	}
	if !errors.Is(err, ErrNotFound) {
		return Attempt{}, err
	}
	owner, err := uuid.NewRandom()
	if err != nil {
		return Attempt{}, ErrUnavailable
	}
	b.OwnerID = owner.String()
	var result Attempt
	entered := false
	err = s.ledger.WithInstance(ctx, instanceID, func(scoped Ledger) error {
		entered = true
		if err := ctx.Err(); err != nil {
			return err
		}
		a, execute, err := scoped.Admit(ctx, b, "")
		if err != nil {
			return err
		}
		if !serviceMatches(a, b) {
			return ErrConflict
		}
		result = a
		if !execute {
			return nil
		}
		if a.State != Preparing {
			return ErrUnavailable
		}
		// Once admission committed, an HTTP cancellation cannot abandon the
		// owned operation. Work is synchronous: no goroutine can outlive the
		// scoped session or release a client lease during Send.
		opCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), serviceOperationTimeout)
		defer cancel()
		workCtx, stop := context.WithTimeout(opCtx, serviceWorkTimeout)
		defer stop()
		if deadlineExpired(b.ValidUntil, s.now) {
			result, err = serviceComplete(opCtx, scoped, b, Rejected, nil, "expired")
			return err
		}
		prepared, prepErr := s.transport.Prepare(workCtx, instanceID, req.MessageID, msg)
		if prepared != nil {
			defer prepared.Close()
		}
		if deadlineExpired(b.ValidUntil, s.now) || errors.Is(prepErr, ErrExpired) {
			result, err = serviceComplete(opCtx, scoped, b, Rejected, nil, "expired")
			return err
		}
		if prepErr != nil || prepared == nil || workCtx.Err() != nil {
			result, err = serviceComplete(opCtx, scoped, b, Rejected, nil, "preparation_failed")
			return err
		}
		// A failed MarkSending can mean its COMMIT succeeded. Never send,
		// reject, or release the durable barrier on that ambiguous response.
		if err := scoped.MarkSending(workCtx, b); err != nil {
			return err
		}
		if deadlineExpired(b.ValidUntil, s.now) {
			result, err = serviceComplete(opCtx, scoped, b, Rejected, nil, "expired")
			return err
		}
		receipt, sendErr := prepared.Send(workCtx) // Exactly one commercial call.
		if errors.Is(sendErr, ErrExpired) && !errors.Is(sendErr, ErrAmbiguousSend) {
			result, err = serviceComplete(opCtx, scoped, b, Rejected, nil, "expired")
		} else if sendErr != nil || workCtx.Err() != nil {
			result, err = serviceComplete(opCtx, scoped, b, Uncertain, nil, "send_uncertain")
		} else if receipt.MessageID != b.MessageID || receipt.AcceptedAt.IsZero() {
			result, err = serviceComplete(opCtx, scoped, b, Uncertain, nil, "receipt_mismatch")
		} else {
			receipt.AcceptedAt = receipt.AcceptedAt.UTC()
			result, err = serviceComplete(opCtx, scoped, b, Accepted, &receipt, "")
		}
		return err
	})
	if errors.Is(err, ErrBusy) && !entered {
		// No callback means no transport work was authorized. Persist a denied
		// attempt on the root ledger, without borrowing the busy lock session.
		if err := ctx.Err(); err != nil {
			return Attempt{}, err
		}
		var execute bool
		result, execute, err = s.ledger.Admit(ctx, b, "instance_busy")
		if err == nil && (execute || !serviceMatches(result, b)) {
			err = ErrUnavailable
		}
	}
	if err != nil {
		return Attempt{}, err
	}
	return result, nil
}

func serviceComplete(ctx context.Context, ledger Ledger, b Binding, state string, receipt *Receipt, code string) (Attempt, error) {
	a, err := ledger.Complete(ctx, b, state, receipt, code)
	if err != nil {
		return Attempt{}, err
	}
	if !serviceMatches(a, b) || a.State != state || a.Code != code {
		return Attempt{}, ErrUnavailable
	}
	if state == Accepted && (a.Receipt == nil || a.Receipt.MessageID != b.MessageID || a.Receipt.AcceptedAt.IsZero()) {
		return Attempt{}, ErrUnavailable
	}
	return a, nil
}

// Presence holds the same scoped session as Send and checks the durable barrier,
// including crash survivors. It cannot authorize a message or clear pending work.
func (s *Service) Presence(ctx context.Context, instanceID string, req PresenceRequest) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if !serviceUUID(instanceID) || len(req.To) > 255 || !utf8.ValidString(req.To) || req.DurationMS < 8000 || req.DurationMS > 26000 {
		return serviceInvalid("presence instance/target/duration")
	}
	if _, err := queueTarget(req.To); err != nil {
		return serviceInvalid("canonical PN/LID/group JID required")
	}
	if s == nil || s.ledger == nil || s.transport == nil {
		return ErrUnavailable
	}
	bounded, cancel := context.WithTimeout(ctx, serviceWorkTimeout)
	defer cancel()
	return s.ledger.WithInstance(bounded, instanceID, func(scoped Ledger) error {
		if err := bounded.Err(); err != nil {
			return err
		}
		if err := scoped.Idle(bounded, instanceID); err != nil {
			return err
		}
		return s.transport.Presence(bounded, instanceID, req.To, req.DurationMS)
	})
}

// Lookup is read-only even for old preparing/sending attempts after a restart.
func (s *Service) Lookup(ctx context.Context, instanceID, attemptID string) (Attempt, error) {
	if err := ctx.Err(); err != nil {
		return Attempt{}, err
	}
	if !serviceUUID(instanceID) || !serviceUUID(attemptID) {
		return Attempt{}, serviceInvalid("canonical instance/attempt UUID required")
	}
	if s == nil || s.ledger == nil {
		return Attempt{}, ErrUnavailable
	}
	return s.ledger.Lookup(ctx, instanceID, attemptID)
}
